#!/usr/bin/env node
// Builds src/styles/tokens.css from design/tokens/*.json (the single source of truth).
// No dependencies. Run: node scripts/build-tokens.mjs
//
// colors.json   -> --color-<semantic path> in :root (light only), and
//                  --<component path> referencing the semantic variables.
// other files   -> --<group>-<path> for every leaf token.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokenDir = join(root, 'design', 'tokens');
const outFile = join(root, 'src', 'styles', 'tokens.css');

const read = (f) => JSON.parse(readFileSync(join(tokenDir, f), 'utf8'));
const isToken = (n) => n && typeof n === 'object' && '$value' in n;
const get = (obj, path) => path.split('.').reduce((n, k) => (n == null ? n : n[k]), obj);

function leaves(node, path = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (isToken(v)) out.push([[...path, k], v.$value]);
    else if (v && typeof v === 'object') leaves(v, [...path, k], out);
  }
  return out;
}

// Follow {primitive.x.y} aliases down to a literal value.
function resolveLiteral(data, value, depth = 0) {
  if (typeof value !== 'string' || !/^\{.+\}$/.test(value)) return value;
  if (depth > 12) throw new Error(`Alias loop at ${value}`);
  const node = get(data, value.slice(1, -1));
  if (!isToken(node)) throw new Error(`Unresolved alias ${value}`);
  return resolveLiteral(data, node.$value, depth + 1);
}

const decl = (name, value) => `  --${name}: ${value};`;
const lines = [];
lines.push('/* GENERATED by scripts/build-tokens.mjs from design/tokens/*.json. Do not edit by hand. */');

// ---------- colours ----------
const colors = read('colors.json');
const light = leaves(colors.semantic).map(([p, v]) => decl(`color-${p.join('-')}`, resolveLiteral(colors, v)));
const component = leaves(colors.component).map(([p, v]) => {
  const ref = v.match(/^\{semantic\.(.+)\}$/);
  if (!ref) throw new Error(`Component token ${p.join('.')} must reference a semantic token`);
  return decl(p.join('-'), `var(--color-${ref[1].replace(/\./g, '-')})`);
});

// ---------- everything else ----------
const other = [];
for (const file of readdirSync(tokenDir).filter((f) => f.endsWith('.json') && f !== 'colors.json').sort()) {
  const data = read(file);
  other.push(`  /* ${file} */`);
  for (const [p, v] of leaves(data)) {
    const value = typeof v === 'string' && /^\{.+\}$/.test(v) ? `var(--${v.slice(1, -1).replace(/\./g, '-')})` : v;
    other.push(decl(p.join('-'), value));
  }
}

lines.push(':root {', '  color-scheme: light;', '  /* colors.json: semantic (light) */', ...light,
  '  /* colors.json: component */', ...component, ...other, '}', '');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'));
console.log(`Wrote ${outFile} (${light.length} colour, ${component.length} component, ${other.length} other declarations)`);
